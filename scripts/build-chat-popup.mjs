// Builds chat_popup/: the website's chat assistant ("Jago") on a page of its own, for the
// chat service to serve at /chat_popup/ and for testing the service. It is made from the
// component kit, so it looks and works like the assistant on the website. Run after
// `npm run kit:build`:
//
//   npm run chat:build
//
// Writes index.html (English), hi/index.html (Hindi) and copies of the kit files they use.
// Leaves config.js (the address questions are sent to) and README.md as they are.

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const kit = path.join(root, 'packages/dbim-kit');
const out = path.join(root, 'chat_popup');

// Kit files the pages use; dbim.min.css loads the fonts and the two SVG files in assets/.
const FILES = [
  'dbim.min.css', 'dbim.js', 'dbim-early.js', 'icons.svg',
  'fonts/noto-sans-latin.woff2', 'fonts/noto-sans-latin-ext.woff2', 'fonts/noto-sans-devanagari.woff2',
  'assets/jago-96.webp', 'assets/jago-160.webp', 'assets/favicon.png', 'assets/cursor-big.svg', 'assets/warli-band.svg',
];

// Page text the kit templates do not carry. The assistant's own text (name, labels,
// languages, suggested questions) comes from src/data/assistant.ts through the templates.
const TEXT = {
  en: {
    kit: '.',
    org: 'Ministry of Tribal Affairs, Government of India',
    intro: (name, button) => `Ask ${name} about schemes, scholarships, eligibility or any tribal welfare programme. To start, use the “${button}” button at the bottom right of the page.`,
    none: (name) => `I can’t reach the ${name} service right now. Please try again later, or search the Ministry’s website:`,
    search: 'https://tribal.gov.in/search/',
    website: 'https://tribal.gov.in/',
    other: { href: 'hi/', lang: 'hi', label: 'हिन्दी' },
  },
  hi: {
    kit: '..',
    org: 'जनजातीय कार्य मंत्रालय, भारत सरकार',
    intro: (name, button) => `${name} से योजनाओं, छात्रवृत्तियों, पात्रता या किसी भी जनजातीय कल्याण कार्यक्रम के बारे में पूछें। शुरू करने के लिए पृष्ठ के नीचे दाईं ओर “${button}” बटन का उपयोग करें।`,
    none: (name) => `अभी ${name} सेवा से संपर्क नहीं हो पा रहा है। कृपया बाद में फिर से प्रयास करें या मंत्रालय की वेबसाइट पर खोजें:`,
    search: 'https://tribal.gov.in/hi/search/',
    website: 'https://tribal.gov.in/hi/',
    other: { href: '../', lang: 'en', label: 'English' },
  },
};

const attr = (s) => s.replace(/&(?![a-z#0-9]+;)/gi, '&amp;').replace(/"/g, '&quot;');

/** Text inside the first match of `re`; stops the build if the kit template has changed. */
function pick(html, re, what) {
  const m = html.match(re);
  if (!m) throw new Error(`${what} not found in the kit template`);
  return m[1].trim();
}
/** Replaces the one match of `re`; stops the build if there is not exactly one. */
function once(html, re, to, what) {
  const n = html.match(new RegExp(re.source, 'g'))?.length ?? 0;
  if (n !== 1) throw new Error(`${what}: expected one match in the kit template, found ${n}`);
  return html.replace(re, () => to);
}

async function page(lang) {
  const t = TEXT[lang];
  const template = async (file) => (await fs.readFile(path.join(kit, 'templates', lang, file), 'utf8'))
    .replace(/^\s*<!--[\s\S]*?-->\s*/, '') // the kit's note to integrators
    .replaceAll('{{KIT}}', t.kit)
    .trim();

  let tribot = await template('tribot.html');
  const name = pick(tribot, /class="tribot__name">([^<]+)</, 'Assistant name');
  const sub = pick(tribot, /class="tribot__sub">([^<]+)</, 'Assistant description');
  const button = pick(tribot, /class="tribot__fab-label">([^<]+)</, 'Button label');
  // No search index on this page: the fallback links to the website's search instead.
  tribot = once(tribot, /<div class="tribot" data-tribot /, `<div class="tribot" data-tribot data-search-url="${t.search}" `, 'Assistant root');
  tribot = once(tribot, /data-l-none="[^"]*"/, `data-l-none="${attr(t.none(name))}"`, 'Message when the service fails');

  // Only the external-link notice (GIGW hyperlink policy) of the website's dialogs.
  const notice = pick(await template('dialogs.html'), /(<dialog class="panel ext-dialog"[\s\S]*?<\/dialog>)/, 'External-link notice');

  return `<!doctype html>
<!-- Generated by scripts/build-chat-popup.mjs from the component kit (npm run chat:build); do not
     edit by hand. The address questions are sent to is set in config.js; see README.md. -->
<html lang="${lang}" dir="ltr" data-dbim-group="9" data-theme="light" data-text="0">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${name} | ${t.org}</title>
  <meta name="description" content="${attr(sub)}">
  <meta name="theme-color" content="#3E170E">
  <link rel="icon" href="${t.kit}/assets/favicon.png" type="image/png">
  <link rel="stylesheet" href="${t.kit}/dbim.min.css">
  <script src="${t.kit}/dbim-early.js"></script>
</head>
<body>
  <main id="main" tabindex="-1">
    <div class="page-hero"> <div class="container page-hero__inner"> <div> <h1>${name}</h1> <p class="page-hero__lead">${sub}</p> </div> </div> </div>
    <div class="container page-body page-body--wide">
      <div class="prose">
        <p>${t.intro(name, button)}</p>
        <p><a href="${t.other.href}" lang="${t.other.lang}" hreflang="${t.other.lang}">${t.other.label}</a> · <a href="${t.website}">tribal.gov.in</a></p>
      </div>
    </div>
  </main>
  ${tribot}
  ${notice}
  <script src="${t.kit}/config.js"></script>
  <script src="${t.kit}/dbim.js"></script>
</body>
</html>
`;
}

for (const f of FILES) {
  await fs.mkdir(path.dirname(path.join(out, f)), { recursive: true });
  await fs.copyFile(path.join(kit, 'dist', f), path.join(out, f));
}
await fs.mkdir(path.join(out, 'hi'), { recursive: true });
await fs.writeFile(path.join(out, 'index.html'), await page('en'));
await fs.writeFile(path.join(out, 'hi', 'index.html'), await page('hi'));
console.log(`chat_popup/: index.html, hi/index.html and ${FILES.length} kit files`);
